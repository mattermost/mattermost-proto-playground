#!/usr/bin/env node
/**
 * Writes:
 * - compassIconImports.generated.ts — lazy loaders for the guidelines iconography grid
 * - compassIcons.generated.ts — sync registry for Storybook icon select controls
 *
 * Package-style imports so Vite transforms CommonJS compass icons in dev
 * (globbing raw *.js under node_modules bypasses that and causes
 * "exports is not defined").
 */
import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const mod = require('@mattermost/compass-icons/IconGlyphs.js');
const glyphs = Array.isArray(mod) ? mod : mod.default ?? [];

function toPascalIconName(glyph) {
  return (
    glyph
      .split('-')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join('') + 'Icon'
  );
}

const loadersPath = join(
  __dirname,
  '../src/guidelines/foundations/iconography/compassIconImports.generated.ts',
);

const loadersBody = glyphs
  .map(
    (g) =>
      `  '${g}': () => import('@mattermost/compass-icons/components/${g}'),`,
  )
  .join('\n');

const loadersContent = `/* Generated by scripts/gen-compass-icon-manifest.mjs — do not edit by hand */
import type { ComponentType, SVGProps } from 'react';

export type CompassSvgIcon = ComponentType<
  SVGProps<SVGSVGElement> & { size?: string | number }
>;

export const COMPASS_ICON_LOADERS: Record<
  string,
  () => Promise<{ default: CompassSvgIcon }>
> = {
${loadersBody}
};
`;

writeFileSync(loadersPath, loadersContent, 'utf8');
console.log(`Wrote ${glyphs.length} compass icon loaders to ${loadersPath}`);

const storybookDir = join(
  __dirname,
  '../packages/compass-ui/src/storybook',
);
mkdirSync(storybookDir, { recursive: true });

const storybookPath = join(storybookDir, 'compassIcons.generated.ts');

const imports = glyphs
  .map((g) => {
    const name = toPascalIconName(g);
    return `import ${name} from '@mattermost/compass-icons/components/${g}';`;
  })
  .join('\n');

const entries = glyphs
  .map((g) => `  '${g}': ${toPascalIconName(g)},`)
  .join('\n');

const storybookContent = `/* Generated by scripts/gen-compass-icon-manifest.mjs — do not edit by hand */
import type { ComponentType, SVGProps } from 'react';
${imports}

export type CompassSvgIcon = ComponentType<
  SVGProps<SVGSVGElement> & { size?: string | number }
>;

export const STORYBOOK_ICONS = {
${entries}
} as const satisfies Record<string, CompassSvgIcon>;

export type StorybookIconName = keyof typeof STORYBOOK_ICONS;

export const STORYBOOK_ICON_NAMES = Object.keys(
  STORYBOOK_ICONS,
) as StorybookIconName[];
`;

writeFileSync(storybookPath, storybookContent, 'utf8');
console.log(
  `Wrote ${glyphs.length} Storybook icon registry entries to ${storybookPath}`,
);
