#!/usr/bin/env node
/**
 * Writes compassIconImports.generated.ts — package-style dynamic imports so Vite
 * transforms CommonJS compass icons in dev (globbing raw *.js under node_modules
 * bypasses that and causes "exports is not defined").
 */
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const mod = require('@mattermost/compass-icons/IconGlyphs.js');
const glyphs = Array.isArray(mod) ? mod : mod.default ?? [];

const outPath = join(
  __dirname,
  '../src/guidelines/foundations/iconography/compassIconImports.generated.ts',
);

const body = glyphs
  .map(
    (g) =>
      `  '${g}': () => import('@mattermost/compass-icons/components/${g}'),`,
  )
  .join('\n');

const content = `/* Generated by scripts/gen-compass-icon-manifest.mjs — do not edit by hand */
import type { ComponentType, SVGProps } from 'react';

export type CompassSvgIcon = ComponentType<
  SVGProps<SVGSVGElement> & { size?: string | number }
>;

export const COMPASS_ICON_LOADERS: Record<
  string,
  () => Promise<{ default: CompassSvgIcon }>
> = {
${body}
};
`;

writeFileSync(outPath, content, 'utf8');
console.log(`Wrote ${glyphs.length} compass icon loaders to ${outPath}`);
